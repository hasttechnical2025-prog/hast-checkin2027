-- gen_random_uuid() + crypt()/gen_salt() cho PIN (bcrypt = bf).
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- ---------------------------------------------------------------------
-- NHÂN VIÊN — danh bạ + định danh (token) + PIN
-- name KHÔNG còn UNIQUE (trùng tên được, phân biệt bằng ma_nv).
-- ma_nv do Admin gán tay lúc tạo, định dạng ST001..ST999.
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_employees (
  id               int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ma_nv            text UNIQUE NOT NULL,
  name             text NOT NULL,
  email            text,
  telegram_chat_id bigint,
  department       text NOT NULL,
  role             text NOT NULL DEFAULT 'CBNV',          -- 'CBNV' | 'TBP'
  loai_ca          text NOT NULL DEFAULT 'tieu_chuan',    -- tieu_chuan | ngoai_le_1 | ngoai_le_2
  status           text NOT NULL DEFAULT 'Đang làm việc', -- 'Đang làm việc' | 'Đã nghỉ việc'
  pin_hash         text,                                  -- bcrypt (pgcrypto bf); PIN 4 số
  token            uuid UNIQUE NOT NULL DEFAULT gen_random_uuid(), -- định danh path /c/[token], thu hồi được
  mien_cham_cong   boolean NOT NULL DEFAULT false,
  ngay_vao_lam     date,
  created_at       timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chamcong_employees_ma_nv_format CHECK (ma_nv ~ '^ST[0-9]{3}$'),
  CONSTRAINT chamcong_employees_role_chk CHECK (role IN ('CBNV','TBP')),
  CONSTRAINT chamcong_employees_loai_ca_chk CHECK (loai_ca IN ('tieu_chuan','ngoai_le_1','ngoai_le_2'))
);

-- ---------------------------------------------------------------------
-- CẤU HÌNH NGƯỠNG CHẤM ĐIỂM A/B/D (data-driven) — Admin sửa, không cần deploy
--   IN  (morning_in, afternoon_in): dùng a_end (mốc cuối A) + b_end (mốc cuối B; null = không có B)
--   OUT sáng (morning_out):         dùng a_start (đầu A) + a_end2 (cuối A)
--   OUT chiều (afternoon_out):      dùng a_end (mốc >= a_end là A; có chấm mà sớm hơn = B; null = D)
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_shift_config (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shift_type text NOT NULL,   -- tieu_chuan | ngoai_le_1 | ngoai_le_2
  session    text NOT NULL,   -- morning_in | morning_out | afternoon_in | afternoon_out
  a_start    time,
  a_end      time,
  a_end2     time,
  b_end      time,
  updated_at timestamptz NOT NULL DEFAULT now(),
  updated_by text,
  UNIQUE (shift_type, session)
);

-- ---------------------------------------------------------------------
-- NGÀY NGHỈ LỄ
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_holidays (
  date        date PRIMARY KEY,
  description text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- NỘI DUNG HƯỚNG DẪN (overlay) — id = p1..p4
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_guide_content (
  id         text PRIMARY KEY,
  title      text,
  content    text,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- CẤU HÌNH HỆ THỐNG (key/value): tên công ty, GPS, công tắc gộp ốm...
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_system_config (
  key        text PRIMARY KEY,
  value      text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------
-- CẤU HÌNH IN BẢNG NSCL (tách khỏi cột password đa mục đích của app cũ)
-- Singleton: giữ đúng 1 dòng (id = 1).
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_nscl_print_config (
  id         int PRIMARY KEY DEFAULT 1,
  config     jsonb NOT NULL DEFAULT '{}'::jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT chamcong_nscl_print_singleton CHECK (id = 1)
);
