-- ---------------------------------------------------------------------
-- LOG CHẤM THÔ (append-only) — mỗi lần chạm 1 dòng
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_attendance_logs (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id    int  NOT NULL REFERENCES chamcong_employees(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  employee_name  text,                               -- denorm (hiển thị/Excel)
  checked_at     timestamptz NOT NULL DEFAULT now(), -- UTC; trigger đổi sang giờ VN
  latitude       numeric,
  longitude      numeric,
  accuracy       numeric,
  address        text,
  nearest_office text,
  distance       numeric,
  status         text,
  note           text,
  device_id      uuid                                -- thiết bị đã chấm (chamcong_device_bind.device_id)
);

-- ---------------------------------------------------------------------
-- BẢN GHI NGÀY (tổng hợp tự động bởi trigger 0004) — 1 dòng / người / ngày
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_attendance_records (
  id                 uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id        int  NOT NULL REFERENCES chamcong_employees(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  employee_name      text,
  date               date NOT NULL,
  morning_in         time,
  morning_out        time,
  afternoon_in       time,
  afternoon_out      time,
  grades             text NOT NULL DEFAULT 'D,D,D,D',   -- CSV "A,B,A,D"
  note               text,
  justification      text,
  justification_type text,                              -- phep | om | khac
  justification_buoi text,                              -- ca_ngay | sang | chieu
  approve_status     text NOT NULL DEFAULT 'Chờ',       -- Chờ | Đồng ý | Từ chối
  approve_note       text,
  approve_time       timestamptz,
  nscl_score         text,                              -- 1..15 hoặc P/Ô/N/5
  nscl_adjust        numeric,
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (employee_id, date)
);

-- ---------------------------------------------------------------------
-- KÝ & KHÓA bảng điểm NSCL theo phòng / tháng
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_nscl_lock (
  id           int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  department   text NOT NULL,
  thang        int  NOT NULL,
  nam          int  NOT NULL,
  nguoi_ky     text,
  thoi_gian_ky timestamptz NOT NULL DEFAULT now(),
  UNIQUE (department, thang, nam)
);

-- ---------------------------------------------------------------------
-- BIND THIẾT BỊ (chống chấm hộ): 1 tài khoản = 1 thiết bị đang hoạt động
-- device_id = token do server cấp khi bind (bền, không dùng fingerprint).
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_device_bind (
  id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id    int  NOT NULL REFERENCES chamcong_employees(id) ON DELETE CASCADE,
  device_id      uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
  device_label   text,                               -- UA/tên máy để TBP nhận biết
  approve_status text NOT NULL DEFAULT 'Chờ',         -- Chờ | Đồng ý | Từ chối
  approved_by    text,
  is_active      boolean NOT NULL DEFAULT false,
  bound_at       timestamptz NOT NULL DEFAULT now(),
  approved_at    timestamptz
);

-- Mỗi nhân viên chỉ 1 thiết bị ĐANG hoạt động.
CREATE UNIQUE INDEX uq_device_active_per_emp
  ON chamcong_device_bind (employee_id) WHERE is_active;

-- ---------------------------------------------------------------------
-- NGHỈ PHÉP đồng bộ từ app "Sổ Công tác" (webhook một chiều, CHỈ ĐỌC + overlay)
-- Khóa nối = ma_nv (thay khóa họ tên cũ). nhan_vien_la: ma_nv không map được.
-- ---------------------------------------------------------------------
CREATE TABLE chamcong_nghi_phep_dong_bo (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  ma_nv         text,
  employee_id   int REFERENCES chamcong_employees(id) ON DELETE SET NULL,  -- resolve từ ma_nv
  employee_name text,                               -- snapshot để hiển thị
  ngay          date NOT NULL,
  buoi          text NOT NULL DEFAULT 'ca_ngay',    -- ca_ngay | sang | chieu
  loai          text NOT NULL DEFAULT 'phep',       -- phep | om | viec_rieng
  nguon_id      uuid NOT NULL,                       -- id đơn gốc bên Sổ Công tác
  nhan_vien_la  boolean NOT NULL DEFAULT false,
  synced_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (nguon_id, ngay)
);
